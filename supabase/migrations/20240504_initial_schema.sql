ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE page_content ENABLE ROW LEVEL SECURITY;
ALTER TABLE plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE services ENABLE ROW LEVEL SECURITY;
ALTER TABLE customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory ENABLE ROW LEVEL SECURITY;
ALTER TABLE plan_clicks ENABLE ROW LEVEL SECURITY;

-- Simple public read policies (optional, adjust as needed)
CREATE POLICY "Public read page_content" ON page_content FOR SELECT USING (true);
CREATE POLICY "Public read plans" ON plans FOR SELECT USING (true);
CREATE POLICY "Public read services" ON services FOR SELECT USING (true);

-- Authenticated write policies
CREATE POLICY "Auth manage users" ON users ALL TO authenticated USING (true);
CREATE POLICY "Auth manage page_content" ON page_content ALL TO authenticated USING (true);
CREATE POLICY "Auth manage plans" ON plans ALL TO authenticated USING (true);
CREATE POLICY "Auth manage services" ON services ALL TO authenticated USING (true);
CREATE POLICY "Auth manage customers" ON customers ALL TO authenticated USING (true);
CREATE POLICY "Auth manage inventory" ON inventory ALL TO authenticated USING (true);
CREATE POLICY "Auth manage plan_clicks" ON plan_clicks ALL TO authenticated USING (true);
